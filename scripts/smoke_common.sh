#!/usr/bin/env bash
set -euo pipefail
repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
export PATH="$HOME/.dotnet:$HOME/.local/bin:$PATH" DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
export TMPDIR="${TMPDIR:-/tmp}"
mkdir -p "$TMPDIR"
smoke_dir=$(mktemp -d "$TMPDIR/civicops-smoke.XXXXXX")
smoke_port=$(python3 -c 'import socket;s=socket.socket();s.bind(("127.0.0.1",0));print(s.getsockname()[1]);s.close()')
export CIVICOPS_DATA_DIR="$smoke_dir/data" CIVICOPS_DEMO_MODE=${SMOKE_DEMO_MODE:-true} CIVICOPS_EMAIL_MODE=outbox
export CIVICOPS_DISPATCH_TOKEN=test-smoke-dispatch-token
export CIVICOPS_SECRET_PROVIDER=env
# Owner-mounted credentials must never enter an isolated offline smoke implicitly.
for secret_name in CIVICOPS_OIDC_CLIENT_SECRET CIVICOPS_LLM_API_KEY ELEVENLABS_API_KEY CIVICOPS_ELEVENLABS_TOOL_SECRET ELEVENLABS_WEBHOOK_SECRET ZENDESK_API_TOKEN ZENDESK_OAUTH_TOKEN ZENDESK_WEBHOOK_SECRET CIVICOPS_EMAIL_SMTP_PASSWORD CIVICOPS_DISPATCH_TOKEN CIVICOPS_DISPATCHERS CIVICOPS_TRAINING_CLIENTS CIVICOPS_BOOTSTRAP_ADMIN_TOKEN_HASH CIVICOPS_DATABASE_URL CIVICOPS_AUDIT_SIGNING_KEY; do
  export "${secret_name}_FILE="
done
export CIVICOPS_STORAGE=${SMOKE_STORAGE:-file} CIVICOPS_DATABASE_URL='' CIVICOPS_TELEMETRY=off
if [[ "$CIVICOPS_STORAGE" == postgres ]]; then
  [[ ${CIVICOPS_EPHEMERAL_PG:-} == 1 && -n ${CIVICOPS_TEST_DATABASE_URL:-} ]] || {
    echo 'PostgreSQL smoke requires the own-user with_ephemeral_pg.sh wrapper.' >&2; exit 2;
  }
  export CIVICOPS_DATABASE_URL="$CIVICOPS_TEST_DATABASE_URL"
elif [[ "$CIVICOPS_STORAGE" != file ]]; then
  echo 'Smoke storage must be file or postgres.' >&2; exit 2
fi
export CIVICOPS_AUDIT_SIGNING_KEY=${SMOKE_AUDIT_SIGNING_KEY:-} CIVICOPS_AUDIT_EXPORT_DIR=${SMOKE_AUDIT_EXPORT_DIR:-}
export CIVICOPS_INFORMATION_OFFICER_CONTACT='' CIVICOPS_PII_RETENTION_DAYS='' CIVICOPS_EMAIL_SMTP_PASSWORD=''
export CIVICOPS_AUTH_LIMIT=1000 CIVICOPS_TOOL_LIMIT=1000
export CIVICOPS_MAP_TILE_URL=${SMOKE_MAP_TILE_URL:-none} CIVICOPS_MAP_ATTRIBUTION='' CIVICOPS_MAP_CREW_STALE_MINUTES=''
export CIVICOPS_DISPATCHERS=''
for identity_key in PROVIDER AUTHORITY CLIENT_ID CLIENT_SECRET DIRECTORY_ID ROLE_CLAIM GROUP_CLAIM TENANT_CLAIM ROLE_MAP GROUP_MAP TENANT_ID HOSTED_DOMAIN SESSION_MINUTES; do
  export "CIVICOPS_OIDC_${identity_key}="
done
export CIVICOPS_BOOTSTRAP_ADMIN_TOKEN_HASH='' CIVICOPS_BOOTSTRAP_ADMIN_TENANT=''
export CIVICOPS_CREW_OIDC_CLIENT_ID=''
export CIVICOPS_SIP_CALLBACK_SECRET='' CIVICOPS_SIP_CALLBACK_SECRET_FILE=''
export CIVICOPS_CHANNEL_RELAY_PORT='' CIVICOPS_CHANNEL_RELAY_TARGET=''
export CIVICOPS_SOS_LOCATION_WINDOW_MINUTES='' CIVICOPS_SOS_ACK_TARGET_SECONDS='' CIVICOPS_SOS_CANCEL_WINDOW_SECONDS=''
export CIVICOPS_CHANNEL_MODE=''
export CIVICOPS_CHANNEL_ENCRYPTION_KEY=''
export CIVICOPS_CHANNEL_ENCRYPTION_KEY_FILE=''
export CIVICOPS_CHANNEL_INGRESS_SECRET=''
export CIVICOPS_CHANNEL_INGRESS_SECRET_FILE=''
export CIVICOPS_CHANNEL_WEBHOOK_BASE_URL=''
export CIVICOPS_CHANNEL_SEND_ENABLED=''
export CIVICOPS_CHANNEL_RETENTION_DAYS=''
export CIVICOPS_TWILIO_AUTH_TOKEN=''
export CIVICOPS_TWILIO_AUTH_TOKEN_FILE=''
export CIVICOPS_TWILIO_ACCOUNT_SID=''
export CIVICOPS_TWILIO_FROM_NUMBER=''
export CIVICOPS_CLICKATELL_API_KEY=''
export CIVICOPS_CLICKATELL_API_KEY_FILE=''
export CIVICOPS_CLICKATELL_CALLBACK_SECRET=''
export CIVICOPS_CLICKATELL_CALLBACK_SECRET_FILE=''
export CIVICOPS_CLICKATELL_FROM_NUMBER=''
export CIVICOPS_WHATSAPP_APP_SECRET=''
export CIVICOPS_WHATSAPP_APP_SECRET_FILE=''
export CIVICOPS_WHATSAPP_VERIFY_TOKEN=''
export CIVICOPS_WHATSAPP_VERIFY_TOKEN_FILE=''
export CIVICOPS_WHATSAPP_ACCESS_TOKEN=''
export CIVICOPS_WHATSAPP_ACCESS_TOKEN_FILE=''
export CIVICOPS_WHATSAPP_PHONE_NUMBER_ID=''
export CIVICOPS_ELEVENLABS_INBOUND_SIP_URI=''
export CIVICOPS_TRAINING_CLIENTS='' CIVICOPS_CERT_POLICY=warn CIVICOPS_RETENTION_DAYS=''
export CIVICOPS_TRAINING_CERTIFICATIONS_ENABLED=true CIVICOPS_TRAINING_PASS_SCORE=80 CIVICOPS_TRAINING_LIMIT=${SMOKE_REQUEST_LIMIT:-1000}
export CIVICOPS_LLM_BASE_URL=''
export CIVICOPS_LLM_API_KEY=''
export ELEVENLABS_API_KEY=''
export ELEVENLABS_AGENT_ID=''
export ELEVENLABS_AGENT_PHONE_NUMBER_ID=''
export CIVICOPS_ELEVENLABS_TOOL_SECRET=''
export ELEVENLABS_WEBHOOK_SECRET=test-webhook-secret
export ZENDESK_SUBDOMAIN=''
export ZENDESK_EMAIL=''
export ZENDESK_API_TOKEN=''
export ZENDESK_OAUTH_TOKEN=''
export ZENDESK_WEBHOOK_SECRET=test-webhook-secret
export CIVICOPS_EMAIL_FROM=civicops@example.invalid
export CIVICOPS_EMAIL_NOTIFY_TO=''
export CIVICOPS_EMAIL_SMTP_HOST=''
export CIVICOPS_INTAKE_LIMIT=${SMOKE_REQUEST_LIMIT:-1000} CIVICOPS_DISPATCH_LIMIT=${SMOKE_REQUEST_LIMIT:-1000}
smoke_dll="$repo_root/products/civicops/bin/Release/net10.0/CivicOps.dll"
if [[ ! -f "$smoke_dll" ]]; then dotnet build "$repo_root/CivicOps.sln" -c Release; fi
ASPNETCORE_URLS="http://127.0.0.1:$smoke_port" dotnet "$smoke_dll" --contentRoot "$repo_root/products/civicops" > "$smoke_dir/server.log" 2>&1 &
smoke_pid=$!
cleanup_smoke() { kill "$smoke_pid" 2>/dev/null || true; wait "$smoke_pid" 2>/dev/null || true; rm -rf "$smoke_dir"; }
trap cleanup_smoke EXIT
export SMOKE_BASE_URL="http://127.0.0.1:$smoke_port"
for attempt in $(seq 1 60); do
  if curl --fail --silent "$SMOKE_BASE_URL/healthz" > "$smoke_dir/health.json"; then break; fi
  if ! kill -0 "$smoke_pid" 2>/dev/null; then cat "$smoke_dir/server.log"; exit 1; fi
  sleep .2
done
curl --fail --silent "$SMOKE_BASE_URL/healthz" > /dev/null
